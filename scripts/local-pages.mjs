import { readFileSync } from "node:fs";
import { dirname, relative } from "node:path/posix";
import { parse, serialize } from "parse5";

import { siteRedirects } from "./layout.mjs";
import { assetSourcePath, localPagePath } from "./product-paths.mjs";
import { siteOrigin } from "./validate-site.mjs";

const urlAttributes = new Set(["href", "src", "poster", "data-src", "action"]);
const localScripts = new Set([
  "/appcut/guides/guides.js",
  "/appcut/script.js",
  "/appcut/wind-files.js",
  "/assets/site/calc.js",
  "/assets/site/navigation.js",
  "/assets/site/page-interactions.js",
  "/assets/site/preferences.js",
  "/scripts.js",
]);
const cssUrl = /url\(\s*(?:"([^"]*)"|'([^']*)'|([^)'"]*?))\s*\)/gi;
const localMasks = new Map();
const embedClasses = new Set(["typeform-wrapper", "tally-status", "tally-retry"]);

function siteUrl(value, route) {
  const target = new URL(value, siteOrigin + "/" + route);
  const isBricks = target.hostname === "bricks.pe" || target.hostname === "www.bricks.pe";
  return isBricks && ["https:", "http:"].includes(target.protocol) ? target : null;
}

export function localFileHref(value, route, routes) {
  if (!value.trim() || value.startsWith("#") || value.startsWith("?")) return value;
  const target = siteUrl(value, route);
  if (!target) return value.startsWith("//") ? "https:" + value : value;

  const path = target.pathname.slice(1);
  const index = path ? path.replace(/\/?$/, "/") + "index.html" : "index.html";
  const isPage = routes.has(path) || routes.has(index);
  const redirect = siteRedirects.get(path) ?? siteRedirects.get(index);
  if (redirect) return localFileHref(redirect + target.search + target.hash, route, routes);
  const page = routes.has(path) ? path : index;
  const file = isPage ? localPagePath(page) : assetSourcePath(path);
  return relative(dirname(localPagePath(route)), file) + target.search + target.hash;
}

function pageStyle(value, route, routes) {
  return value.replace(cssUrl, (original, double, single, bare, offset) => {
    const url = double ?? single ?? bare;
    if (!url || url.startsWith("#")) return original;
    const target = siteUrl(url, route);
    if (!target) return original;
    const path = target.pathname;
    const isMask = /mask-image:\s*$/i.test(value.slice(0, offset));
    if (isMask && /^\/images(?:-[\w-]+)?\/[\w-]+\.svg$/.test(path)) {
      // Browsers block external SVG masks in file pages.
      if (!localMasks.has(path)) localMasks.set(path, readFileSync(new URL("../" + assetSourcePath(path.slice(1)), import.meta.url)).toString("base64"));
      return `url("data:image/svg+xml;base64,${localMasks.get(path)}")`;
    }
    return `url("${localFileHref(url, route, routes)}")`;
  });
}

export function renderLocalPage(html, route, routes) {
  const document = parse(html);
  const attr = (node, name) => node.attrs?.find(item => item.name === name)?.value;

  function include(node) {
    if (node.nodeName === "#comment") return node.data.trim() !== "site:analytics";
    if (node.tagName === "script") {
      const src = attr(node, "src");
      return attr(node, "type") === "application/ld+json" || (src && localScripts.has(siteUrl(src, route)?.pathname));
    }
    if (node.tagName === "link") {
      return !["manifest", "preconnect", "dns-prefetch", "preload"].includes(attr(node, "rel")) ||
        (attr(node, "rel") === "preload" && siteUrl(attr(node, "href"), route));
    }
    if (node.tagName === "noscript") return node.childNodes.every(child => !/<(?:iframe|img)\b/i.test(child.value ?? ""));
    if (node.tagName === "iframe") return false;
    if (attr(node, "id") === "cookie-consent-banner") return false;
    return !attr(node, "class")?.split(/\s+/).some(name => embedClasses.has(name));
  }

  function prepare(node) {
    const rel = attr(node, "rel");
    if (node.tagName === "script" && attr(node, "type") === "module") {
      node.attrs = node.attrs.filter(item => item.name !== "type");
      node.attrs.push({ name: "defer", value: "" });
    }
    for (const attribute of node.attrs ?? []) {
      if (urlAttributes.has(attribute.name) && !["canonical", "alternate"].includes(rel)) {
        attribute.value = localFileHref(attribute.value, route, routes);
      } else if (["srcset", "data-srcset"].includes(attribute.name)) {
        attribute.value = attribute.value.replace(/(\s*)([^\s,]+(?:,[^\s,]+)*)([^,]*)(,|$)/g,
          (_, gap, url, descriptor, comma) => gap + localFileHref(url, route, routes) + descriptor + comma);
      } else if (attribute.name === "style") {
        attribute.value = pageStyle(attribute.value, route, routes);
      }
    }
    node.childNodes = (node.childNodes ?? []).filter(include);
    for (const child of node.childNodes) {
      if (node.tagName === "style" && child.nodeName === "#text") child.value = pageStyle(child.value, route, routes);
      prepare(child);
    }
  }

  prepare(document);
  return serialize(document).replace("<!DOCTYPE html>", `<!DOCTYPE html>
<!-- Generated by npm run build. Edit the shell under the app’s pages/ or shared content/pages/. -->`).replace(/[ \t]+$/gm, "").trimEnd() + "\n";
}
